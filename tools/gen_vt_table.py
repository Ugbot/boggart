#!/usr/bin/env python3
"""Translate the pinned Ghostty single/range transition declarations to C data."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def generate(upstream):
    manifest = json.loads((ROOT / "THIRD_PARTY/ghostty-port.json").read_text())
    sources = {}
    for name in ("Parser.zig", "parse_table.zig"):
        path = "src/terminal/" + name
        content = (upstream / path).read_bytes()
        entry = next(m for m in manifest["modules"] if m["upstream_path"] == path)
        assert hashlib.sha256(content).hexdigest() == entry["sha256"], "unexpected upstream: " + path
        sources[name] = content.decode()
    def enum(name):
        body = re.search(r"pub const " + name + r" = enum \{(.*?)\};", sources["Parser.zig"], re.S)[1]
        return re.findall(r"^\s*(\w+),", body, re.M)
    states, actions = enum("State"), enum("TransitionAction")
    assert len(states) == 14 and len(actions) < 16
    header = (ROOT / "src/lvt.h").read_text()
    for name, prefix, values in (("lvt_state", "LVT_", states),
                                  ("lvt_action", "LVT_A_", actions)):
        body = re.search(r"typedef enum \{([^}]+)\} " + name + ";", header, re.S)[1]
        names = [item.strip() for item in body.split(",")][:-1]
        assert names == [prefix + value.upper() for value in values], "C enum ordering differs: " + name
    table = [[i << 4 for _ in range(256)] for i in range(len(states))]
    body = sources["parse_table.zig"].split("fn genTable() Table {", 1)[1].split("// Create our immutable version", 1)[0]
    body = re.sub(r"//[^\n]*", "", body)
    pattern = re.compile(r"const source(?:\s*:\s*State)?\s*=\s*([^;]+);|"
                         r"(single|range)\(&result,\s*([^;]+)\);")
    source = None
    count = 0
    for match in pattern.finditer(body):
        if match[1]:
            value = match[1].strip()
            source = value.removeprefix("State.") if value.startswith("State.") else "all"
            continue
        args = [a.strip() for a in match[3].split(",")]
        expected = 4 if match[2] == "single" else 5
        assert len(args) == expected
        if expected == 4:
            lo = hi = int(args[0], 0)
        else:
            lo, hi = int(args[0], 0), int(args[1], 0)
        before, after, action = args[-3:]
        before = source if before == "source" else before.removeprefix(".")
        after = source if after == "source" else after.removeprefix(".")
        targets = states if before == "all" else [before]
        for state in targets:
            next_state = state if after == "all" else after
            packed = (states.index(next_state) << 4) | actions.index(action.removeprefix("."))
            for byte in range(lo, hi + 1): table[states.index(state)][byte] = packed
        count += 1
    assert count == len(re.findall(r"(?:single|range)\(&result,", body)), "unparsed transition declaration"
    assert count > 100
    out = ["/* Generated by tools/gen_vt_table.py; do not edit.",
           " * ported from ghostty@" + manifest["revision"] + " src/terminal/parse_table.zig",
           " * Copyright (c) 2024 Mitchell Hashimoto, Ghostty contributors",
           " * SPDX-License-Identifier: MIT; see THIRD_PARTY/ghostty-LICENSE.",
           " */", "static const unsigned char lvt_table[LVT_STATE_COUNT][256] = {"]
    for state, row in zip(states, table):
        out.append("  { /* " + state + " */")
        for i in range(0, 256, 16): out.append("    " + ",".join(str(n) for n in row[i:i + 16]) + ",")
        out.append("  },")
    out.append("};")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "src/vt_table.h"
    content = generate(args.upstream)
    if args.check:
        assert output.read_text() == content, "generated VT table differs"
        print("VT table matches pinned upstream declarations")
    else:
        output.write_text(content)
