#!/usr/bin/env python3
"""Validate and compress the pinned terminal Unicode export into offline C data."""
import argparse
import json
from pathlib import Path

from build_oracle import ROOT, PIN_PATH, sha

FIXTURE = ROOT / 'tests/fixtures/ghostty-unicode-profile.json'
HEADER = ROOT / 'src/btunicode_data.h'
CLASSES = ('other', 'prepend', 'regional_indicator', 'spacing_mark', 'l', 'v', 't', 'lv', 'lvt',
    'zwj', 'zwnj', 'extended_pictographic', 'emoji_modifier_base', 'emoji_modifier',
    'indic_conjunct_break_extend', 'indic_conjunct_break_linker_extend',
    'indic_conjunct_break_linker_other', 'indic_conjunct_break_consonant')


def tables(report):
    pin = json.loads(PIN_PATH.read_text())
    if report['schema'] != 1 or report['kind'] != 'pinned-sdk-terminal-unicode' or any(
        report[k] != pin[k] for k in ('revision', 'archive_sha256', 'zig_version')):
        raise ValueError('Unicode profile pin mismatch')
    if report['uucode_package_hash'] != 'uucode-0.2.0-ZZjBPuuFVgC8YZ8eld4fOKsZANLIhTFMzULQxhkLi1C7' or not report['dependencies'] or report['dependency_lock_sha256'] != 'b878e4fc36f9c2b6c9ad82e5ceba58c91905fde89f0ac3d3cb7ab413ea029e39':
        raise ValueError('missing pinned uucode dependency')
    for key, file in [('driver_sha256', 'probe_unicode_profile.py'), ('probe_sha256', 'unicode_profile.zig')]:
        if report[key] != sha(Path(__file__).with_name(file)):
            raise ValueError('Unicode export source changed')
    values, transitions, classes, states = [], {}, {}, []
    for sample in report['samples']:
        if set(sample) == {'range'}:
            lo, hi, value = sample['range']
            if any(type(v) is not int for v in (lo, hi, value)) or lo != len(values) or not lo <= hi < 0x110000:
                raise ValueError('invalid or noncontiguous property range')
            if not 0 <= value < 512 or value & 3 == 3 or (value >> 3) & 31 >= 18:
                raise ValueError('invalid packed property')
            values.extend([value] * (hi - lo + 1))
        elif set(sample) == {'transition'}:
            key, value = sample['transition']
            if type(key) is not int or type(value) is not int or key in transitions or not 0 <= value <= 9:
                raise ValueError('invalid or duplicate transition')
            transitions[key] = value
        elif set(sample) == {'class'}:
            key, name = sample['class']
            if type(key) is not int or key in classes or type(name) is not str:
                raise ValueError('invalid grapheme class')
            classes[key] = name
        elif set(sample) == {'states'}:
            states.append(sample['states'])
        else:
            raise ValueError('unknown profile record')
    expected = {s | (a << 3) | (b << 8) for s in range(5) for a in range(18) for b in range(18)}
    if classes != dict(enumerate(CLASSES)) or states != [5] or type(states[0]) is not int:
        raise ValueError('grapheme class or state encoding changed')
    if len(values) != 0x110000 or set(transitions) != expected:
        raise ValueError('incomplete Unicode export')
    return values, [transitions.get(i, 0) for i in range(8192)]


def generate(report):
    values, transitions = tables(report)
    pages, indices, known = [], [], {}
    for i in range(0, len(values), 256):
        page = tuple(values[i:i + 256])
        if page not in known:
            known[page] = len(pages); pages.append(page)
        indices.append(known[page])
    if len(pages) > 65536 or any(pages[indices[cp >> 8]][cp & 255] != v for cp, v in enumerate(values)):
        raise ValueError('property compression mismatch')
    lines = ['/* Generated by tools/ghostty/unicode_fixture.py; do not edit.',
        ' * ported from ghostty@05dcf887ef51ea27821f20979493306ec3a19149 src/unicode/props_table.zig',
        ' * Copyright (c) 2024 Mitchell Hashimoto, Ghostty contributors; see THIRD_PARTY/ghostty-LICENSE.',
        ' * Copyright (c) 2026 Jacob Sandlund; see THIRD_PARTY/uucode-LICENSE.',
        ' * Unicode data copyright Unicode, Inc.; see THIRD_PARTY/unicode-LICENSE.',
        ' */', '#include <stdint.h>',
        f'/* Profile SHA256: {sha(FIXTURE)} */']
    def array(name, data, ctype):
        lines.append(f'static const {ctype} {name}[{len(data)}] = {{')
        for i in range(0, len(data), 24):
            lines.append('  ' + ','.join(map(str, data[i:i + 24])) + ',')
        lines.append('};')
    array('btunicode_index', indices, 'uint16_t')
    array('btunicode_pages', [v for page in pages for v in page], 'uint16_t')
    array('btunicode_transitions', transitions, 'uint8_t')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate(json.loads(FIXTURE.read_text()))
    if args.check:
        if HEADER.read_text() != output:
            raise ValueError('stale terminal Unicode table')
    else:
        HEADER.write_text(output)
    print('Pinned terminal Unicode table verified')


if __name__ == '__main__':
    main()
