assert(input:mouse{action='press',button=1,x=16,y=32,cell_width=8,cell_height=16,modifiers=4}); take('\27[<16;3;3M')
assert(input:mouse{action='release',button=1,x=16,y=32,cell_width=8,cell_height=16,modifiers=4}); take('\27[<16;3;3m')
