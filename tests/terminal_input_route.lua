local protocol=require 'terminal'
local Input=assert(loadfile('studio/data/core/terminalinput.lua'))()
local t <close> =protocol.new(80,24,0)
local bytes={}; local input=Input.new(t,function(s) bytes[#bytes+1]=s; return true end,function() return 'paste\n' end)
local function take(expected) local actual=table.concat(bytes); bytes={}; assert(actual==expected,string.format('expected %q got %q',expected,actual)) end
input:key_pressed('ctrl+c'); input:flush(); take('\3')
input:key_pressed('ctrl+v'); input:flush(); take('\22')
t:feed('\27[?1h'); input:key_pressed('up',{key='up',action='press',scancode=82}); take('\27OA')
input:key_released{key='up',action='release',scancode=82}; take('')
input:key_pressed('a',{key='text',unshifted=97,base_layout=97,scancode=4,modifiers=0}); take('')
input:text_input('a'); input:text_input('́'); input:flush(); take('á')
input:key_released{key='text',unshifted=97,scancode=4,modifiers=0}; take('')
input:key_pressed('shift+a',{key='text',unshifted=97,base_layout=97,scancode=4,modifiers=protocol.SHIFT})
input:text_input('A'); input:flush(); take('A')
input:key_pressed('e',{key='text',unshifted=101,scancode=8,modifiers=0})
input:text_editing('´'); input:flush(); take('')
input:key_pressed('e',{key='text',unshifted=101,scancode=8,modifiers=0})
input:text_input('é'); input:flush(); take('é')
input:text_input(('😀'):rep(3000)); take(('😀'):rep(3000))
t:feed('\27[>31u')
input:key_pressed('shift+a',{key='text',unshifted=97,base_layout=97,scancode=4,modifiers=protocol.SHIFT})
input:text_input('A'); input:flush(); take('\27[97:65;2;65u')
input:key_pressed('shift+a',{key='text',unshifted=97,base_layout=97,scancode=4,modifiers=protocol.SHIFT,action='repeat'})
input:text_input('A'); input:flush(); take('\27[97:65;2:2;65u')
input:key_released{key='text',unshifted=97,base_layout=97,scancode=4,modifiers=protocol.SHIFT}; take('\27[97;2:3u')
input:key_pressed('cmd+j',{key='text',unshifted=106,base_layout=106,scancode=13,modifiers=protocol.SUPER}); input:flush(); take('\27[106;9u')
assert(input:key_pressed('ctrl+alt+right',{key='right',modifiers=6,scancode=79})==false); take('')
