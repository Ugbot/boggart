/* utf8width.h -- how wide a run of UTF-8 text is, in monospace columns.
 *
 * Header-only, and deliberately so: the studio's renderer needs this and so
 * does the terminal dashboard's line arithmetic, and those live in two CMake
 * targets whose source lists are written out by hand. A .c file here would be
 * two edits in CMakeLists.txt for four kilobytes of table; an inline one is
 * none. The table is duplicated per translation unit and there are two.
 *
 * WHAT THIS IS FOR. Counting characters is the wrong measure for a grid. A
 * Latin letter, a Japanese ideograph and a combining acute are one codepoint
 * each and take one, two and zero columns. Code that measures in codepoints
 * lays a CJK line out at half the width it draws at, so the text runs past the
 * right edge, wraps in the wrong place, and the caret sits beside the character
 * it claims to be on. That is the bug this exists to remove.
 *
 * WHAT IT IS NOT. This answers "how many cells", not "how does this render":
 *
 *   - No grapheme clustering. A ZWJ emoji sequence (WOMAN + ZWJ + COMPUTER)
 *     measures 2 + 0 + 2 = 4, because that is what a terminal grid does with
 *     it; a shaping engine would draw one 2-wide glyph. Same for a flag, and
 *     for a base letter followed by several marks that a font would compose.
 *   - No shaping and no bidi. Arabic contextual forms and Hebrew/Arabic right-
 *     to-left ordering need HarfBuzz and FriBidi. Widths here are correct for
 *     those scripts; the *order and shape* they are drawn in is not.
 *   - Proportional fonts. This measures a monospace grid. Ask the font for
 *     pixel widths when the font is not monospace.
 *
 * PROVENANCE. UTF8W_ZERO and UTF8W_WIDE are generated by tools/genwidth.py
 * from Unicode 16.0.0's EastAsianWidth.txt, UnicodeData.txt and
 * emoji-data.txt. The rules are Markus Kuhn's wcwidth(): East Asian Wide and
 * Fullwidth are two, nonspacing/enclosing marks and format characters are
 * zero, everything else is one -- brought forward with Emoji_Presentation for
 * the emoji that postdate East Asian Width's original assignments.
 */
