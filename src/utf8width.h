static inline int bog_in_ranges(const bog_range *t, size_t n, uint32_t cp) {
  size_t lo = 0, hi = n;
  while (lo < hi) {
    size_t mid = lo + (hi - lo) / 2;
    if (cp < t[mid].lo)      { hi = mid; }
    else if (cp > t[mid].hi) { lo = mid + 1; }
    else                     { return 1; }
  }
  return 0;
}


/* Columns occupied by one codepoint: 0, 1 or 2.
 *
 * The common case is ASCII and it must not pay for two binary searches, so it
 * is answered before either table is touched. */
static inline int bog_cp_width(uint32_t cp) {
  if (cp >= 0x20 && cp < 0x7f) { return 1; }
  if (cp == 0) { return 0; }
  if (bog_in_ranges(UTF8W_ZERO, sizeof UTF8W_ZERO / sizeof *UTF8W_ZERO, cp)) { return 0; }
  if (bog_in_ranges(UTF8W_WIDE, sizeof UTF8W_WIDE / sizeof *UTF8W_WIDE, cp)) { return 2; }
  return 1;
}


/* Decode one character, advancing past it.
 *
 * A lone continuation byte (0x80..0xbf) reaching the default arm used to be
 * read through `res = *p` on a signed char, which sign-extends to something
 * like 0xffffff80; a caller then shifted that right and indexed an array with
 * the negative result. Nothing that *produces* text emits such a byte, but
 * anything that slices text by byte offset does, and several callers did.
 *
 * So this decodes what it can and treats the rest as one opaque byte rather
 * than trusting the leading byte's advertised length. Malformed input comes
 * back as some codepoint and one byte of progress, which is always safe and
 * always terminates. `end` may be NULL for a NUL-terminated string. */
static inline const char* bog_utf8_next(const char *p, const char *end,
                                        uint32_t *dst) {
  uint32_t res;
  unsigned n;
  unsigned char c = (unsigned char) *p;
  switch (c & 0xf0) {
    case 0xf0 :  res = c & 0x07;  n = 3;  break;
    case 0xe0 :  res = c & 0x0f;  n = 2;  break;
    case 0xd0 :
    case 0xc0 :  res = c & 0x1f;  n = 1;  break;
    default   :  res = c;         n = 0;  break;
  }
  /* Stop at anything that is not a continuation byte, including the string's
   * own terminator: a truncated sequence must not read past the end. */
  while (n--) {
    if (end && p + 1 >= end) { break; }
    if (((unsigned char) p[1] & 0xc0) != 0x80) { break; }
    res = (res << 6) | (uint32_t) (*(++p) & 0x3f);
  }
  *dst = res;
  return p + 1;
}


/* Columns occupied by a whole string. */
static inline int bog_str_width(const char *s, size_t len) {
  const char *p = s, *end = s + len;
  int w = 0;
  uint32_t cp;
  while (p < end) {
    p = bog_utf8_next(p, end, &cp);
    w += bog_cp_width(cp);
  }
  return w;
}


/* The longest prefix of s that fits in `cols` columns, as a byte length.
 *
 * A double-width character straddling the boundary is left out entirely, so
 * the result can be one column short of `cols`. That is the point: half of a
 * CJK glyph is not a thing that can be drawn, and a caller that assumed it
 * filled the row exactly is the caller that produced the off-by-one column of
 * overdraw this replaces. *used, when given, receives the columns actually
 * taken. The cut is always on a character boundary, so the prefix is valid
 * UTF-8 whenever the input was. */
static inline size_t bog_str_take(const char *s, size_t len, int cols,
                                  int *used) {
  const char *p = s, *end = s + len;
  int w = 0;
  uint32_t cp;
  while (p < end) {
    const char *next = bog_utf8_next(p, end, &cp);
    int cw = bog_cp_width(cp);
    if (w + cw > cols) { break; }
    w += cw;
    p = next;
  }
  if (used) { *used = w; }
  return (size_t) (p - s);
}

